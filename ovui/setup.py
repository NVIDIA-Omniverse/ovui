    omni_init = pkg_dir / "__init__.py"
    if not omni_init.exists():
        omni_init.parent.mkdir(parents=True, exist_ok=True)
        omni_init.write_text(
            "# Namespace package - see PEP 420\n"
            "from pkgutil import extend_path\n"
            "__path__ = extend_path(__path__, __name__)\n"
        )


