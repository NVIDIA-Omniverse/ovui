"""
setup.py for ovui

Builds the native shared libraries and pybind11 module via CMake, then packages
them into a wheel alongside the Python sources and resource files (fonts, glyphs).

Usage:
    pip install .
    pip install -e .          # editable / development install
    python -m build           # build wheel
"""

import fnmatch
import hashlib
import json
import os
import platform
import shlex
import shutil
import subprocess
import sys
import sysconfig
from pathlib import Path
from typing import Optional

from setuptools import Extension, setup
from setuptools.command.build_ext import build_ext
from setuptools.command.build_py import build_py

IS_WINDOWS = platform.system() == "Windows"
IS_MACOS = platform.system() == "Darwin"
REPO_ROOT = Path(__file__).resolve().parent.parent
VERSION_FILE = REPO_ROOT / "VERSION.md"
BUILD_INFO_PATH = Path(__file__).resolve().parent / "python" / "omni" / "ui" / "_build_info.py"


def _read_project_version() -> str:
    version = VERSION_FILE.read_text(encoding="utf-8").strip()
    if not version:
        raise RuntimeError(f"{VERSION_FILE} is empty")
    return version


def _read_commit_sha() -> str:
    """Resolve the source commit SHA of the build.

    Resolution order (first non-empty wins):
      1. OVUI_BUILD_COMMIT_SHA — explicit override (set by CI for reproducibility)
      2. GITHUB_SHA — auto-set by GitHub Actions
      3. CI_COMMIT_SHA — auto-set by GitLab CI
      4. `git rev-parse HEAD` from REPO_ROOT — local builds
      5. "unknown"
    """
    for env_var in ("OVUI_BUILD_COMMIT_SHA", "GITHUB_SHA", "CI_COMMIT_SHA"):
        value = os.environ.get(env_var, "").strip()
        if value:
            return value
    try:
        result = subprocess.run(
            ["git", "-C", str(REPO_ROOT), "rev-parse", "HEAD"],
            capture_output=True,
            text=True,
            check=False,
            timeout=10,
        )
        if result.returncode == 0:
            sha = result.stdout.strip()
            if sha:
                return sha
    except (OSError, subprocess.SubprocessError):
        pass
    return "unknown"


def _qualified_version(base_version: str, commit: str) -> str:
    """Return the wheel's PEP 440 version — always the plain base version.

    Public package indexes (PyPI, NVIDIA Kitmaker) reject PEP 440
    local-version identifiers (``+local``), so wheels never carry a
    ``+g<hash>`` suffix. The full commit SHA is still recorded in
    ``_build_info.py`` (via the separate ``__commit__`` field) for
    provenance.
    """
    del commit  # unused; kept in signature for call-site stability
    return base_version


def _write_build_info(version: str, commit: str) -> None:
    """Emit omni/ui/_build_info.py so the installed package exposes
    __version__ and __commit__ at import time. Regenerated on every setup.py
    invocation; the file is gitignored."""
    BUILD_INFO_PATH.parent.mkdir(parents=True, exist_ok=True)
    BUILD_INFO_PATH.write_text(
        "# Auto-generated by ovui/setup.py — do not edit. Gitignored.\n"
        f"__version__ = {version!r}\n"
        f"__commit__ = {commit!r}\n",
        encoding="utf-8",
    )


_PROJECT_VERSION = _read_project_version()
_PROJECT_COMMIT = _read_commit_sha()
_QUALIFIED_VERSION = _qualified_version(_PROJECT_VERSION, _PROJECT_COMMIT)
_write_build_info(_QUALIFIED_VERSION, _PROJECT_COMMIT)


def _executable_name(name: str) -> str:
    return f"{name}.exe" if IS_WINDOWS else name


def _find_tool(name: str, env_var: Optional[str] = None) -> str:
    """Find a build tool without requiring the venv to be activated."""
    if env_var and os.environ.get(env_var):
        return os.environ[env_var]

    candidates = [
        Path(sys.executable).resolve().parent / _executable_name(name),
        Path(sys.prefix).resolve() / ("Scripts" if IS_WINDOWS else "bin") / _executable_name(name),
    ]
    for candidate in candidates:
        if candidate.is_file():
            return str(candidate)

    found = shutil.which(name)
    if found:
        return found

    raise RuntimeError(
        f"{name} is required to build ovui but was not found. "
        f"Install it into this Python environment, for example: "
        f"{sys.executable} -m pip install {name}"
    )


def _windows_fetchcontent_source_args(source_dir: Path, build_dir: Path) -> list:
    """Use local FetchContent source trees on Windows when they are already present.

    Windows development builds are commonly run in locked-down environments where
    CMake cannot clone GitHub dependencies during `pip install`. If a repo-level
    or package-level FetchContent cache already contains the source directories,
    pass them explicitly so `pip install -e ovui` works without shell setup.
    """
    if not IS_WINDOWS:
        return []

    deps_roots = [
        build_dir / "_deps",
        source_dir / "build" / "pip" / "_deps",
        source_dir.parent / "build" / "pip" / "_deps",
    ]
    deps = {
        "FREETYPE": "freetype-src",
        "GLFW": "glfw-src",
    }

    args = []
    for cmake_name, dirname in deps.items():
        for root in deps_roots:
            candidate = root / dirname
            if candidate.is_dir():
                args.append(f"-DFETCHCONTENT_SOURCE_DIR_{cmake_name}={candidate.as_posix()}")
                break
    return args


class CMakeExtension(Extension):
    """A setuptools Extension that delegates to CMake."""

    def __init__(self, name: str):
        super().__init__(name, sources=[])


def _find_artifact(build_dir: Path, subdir: str, filename: str) -> "Path | None":
    """Search for a build artifact in common output locations.

    Multi-config generators (Visual Studio) put binaries in a config subdir.
    """
    candidates = [
        build_dir / subdir / filename,
        build_dir / subdir / "Release" / filename,
        build_dir / subdir / "RelWithDebInfo" / filename,
    ]
    for c in candidates:
        if c.exists():
            return c
    return None


def _use_prebuilt_shared(prebuilt: Path, pkg_dir: Path, scene_pkg_dir: Path,
                         core_libs: list, scene_lib: str, ext_suffix: str) -> None:
    """Replace the four shared binaries with those of a prebuilt ovui folder.

    The folder has the wheel layout (``omni/ui``, ``omni/ui_scene``). Debug
    sections are stripped on Linux; everything else is copied unchanged.
    """
    # On Windows another build's omni.ui.dll may be a plugin, not the
    # forwarder-only DLL of the wheel: only ovui.dll is taken.
    shared_core = [name for name in core_libs if name != "omni.ui.dll"]
    files = [("omni/ui", pkg_dir, name) for name in shared_core + [f"_ui{ext_suffix}"]]
    files += [("omni/ui_scene", scene_pkg_dir, name) for name in (scene_lib, f"_scene{ext_suffix}")]
    strip = None if IS_WINDOWS or IS_MACOS else shutil.which("strip")
    if not IS_WINDOWS and not IS_MACOS and not strip:
        raise RuntimeError("OVUI_PREBUILT_DIR on Linux needs 'strip' to remove debug sections")
    for subdir, dest_dir, name in files:
        src = prebuilt / subdir / name
        if not src.is_file():
            raise RuntimeError(f"OVUI_PREBUILT_DIR has no {subdir}/{name}")
        dest = dest_dir / name
        if dest.exists() or dest.is_symlink():
            dest.unlink()
        shutil.copyfile(str(src), str(dest))
        if strip:
            subprocess.check_call([strip, "--strip-debug", str(dest)])
        print(f"  prebuilt {subdir}/{name}")


class CMakeBuild(build_ext):
    """Custom build_ext that runs cmake to produce the shared libraries."""

    def _generate_sbom(self, build_dir: Path, pkg_dir: Path) -> None:
        """Generate a CycloneDX SBOM and copy it into the package directory.

        Runs two commands against the SBOM tools under ovui/tools/sbom:
          1. conan cyclonedx  — resolves the C++ dep graph and emits CycloneDX JSON
          2. enrich_sbom_licenses.py — adds license text, CPEs, and Python deps

        Both conan and cyclonedx-python-lib are declared in pyproject.toml
        build-system.requires so they are always available here.  The conan
        cyclonedx extension (cmd_cyclonedx.py) is installed on first run via
        `conan config install`; subsequent runs are no-ops because the file
        already exists in the Conan home.
        """
        sbom_tools_dir = REPO_ROOT / "ovui" / "tools" / "sbom"
        conanfile = sbom_tools_dir / "conanfile.py"
        enrich_script = sbom_tools_dir / "enrich_sbom_licenses.py"
        sbom_path = build_dir / "sbom.cdx.json"

        if not conanfile.exists():
            print(f"  [sbom] conanfile.py not found at {conanfile} — skipping")
            return

        try:
            conan = _find_tool("conan")
        except RuntimeError:
            print("  [sbom] conan not found — skipping SBOM generation")
            return

        # Ensure a default profile exists (needed in fresh CI environments).
        subprocess.check_call([conan, "profile", "detect", "--exist-ok"],
                              stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)

        # Ensure the cyclonedx extension is installed in the Conan home.
        import os as _os
        conan_home = Path(_os.path.expanduser("~")) / ".conan2"
        ext_dst = conan_home / "extensions" / "commands" / "cmd_cyclonedx.py"
        if not ext_dst.exists():
            print("  [sbom] installing conan cyclonedx extension ...")
            ext_dst.parent.mkdir(parents=True, exist_ok=True)
            subprocess.check_call([
                conan, "config", "install",
                "https://github.com/conan-io/conan-extensions.git",
                "-sf", "extensions/commands/sbom",
            ], stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
            # conan config install places the file at the conan home root;
            # move it to the correct commands directory if needed.
            misplaced = conan_home / "cmd_cyclonedx.py"
            if misplaced.exists() and not ext_dst.exists():
                shutil.move(str(misplaced), str(ext_dst))

        print("  [sbom] running conan cyclonedx ...")
        subprocess.check_call([
            conan, "cyclonedx",
            "--format", "1.4_json",
            str(conanfile),
            "--no-build-requires",
            "--out-file", str(sbom_path),
        ])

        if enrich_script.exists():
            print("  [sbom] enriching SBOM with license text, CPEs, and Python deps ...")
            subprocess.check_call([
                sys.executable, str(enrich_script),
                "--sbom", str(sbom_path),
            ])

        dst = pkg_dir / "sbom.cdx.json"
        shutil.copy2(str(sbom_path), str(dst))
        print(f"  [sbom] copied sbom.cdx.json -> {dst}")

    def build_extension(self, ext: Extension) -> None:
        # Directories
        source_dir = Path(__file__).resolve().parent
        build_dir = source_dir / "build" / "pip"
        build_dir.mkdir(parents=True, exist_ok=True)

        # Where setuptools wants the final package tree
        ext_fullpath = Path(self.get_ext_fullpath(ext.name)).resolve()
        pkg_dir = ext_fullpath.parent  # .../omni/ui/

        # ---- CMake configure ----
        cmake = _find_tool("cmake", "CMAKE_COMMAND")
        cmake_args = [
            "-DCMAKE_BUILD_TYPE=Release",
            f"-DPYTHON_EXECUTABLE={sys.executable}",
        ]
        cmake_args.extend(_windows_fetchcontent_source_args(source_dir, build_dir))

        # Forward Vulkan hints from environment if available
        vulkan_include = os.environ.get("Vulkan_INCLUDE_DIR", "")
        vulkan_library = os.environ.get("Vulkan_LIBRARY", "")
        if vulkan_include:
            cmake_args.append(f"-DVulkan_INCLUDE_DIR={vulkan_include}")
        if vulkan_library:
            cmake_args.append(f"-DVulkan_LIBRARY={vulkan_library}")

        # RPATH: $ORIGIN on Linux, @loader_path on macOS
        if IS_MACOS:
            cmake_args.extend([
                "-DCMAKE_INSTALL_RPATH=@loader_path",
                "-DCMAKE_BUILD_RPATH=@loader_path",
            ])
        elif not IS_WINDOWS:
            cmake_args.extend([
                "-DCMAKE_INSTALL_RPATH=$ORIGIN",
                "-DCMAKE_BUILD_RPATH=$ORIGIN",
            ])

        # Try to locate pybind11 cmake dir
        try:
            import pybind11
            cmake_args.append(f"-Dpybind11_DIR={pybind11.get_cmake_dir()}")
        except (ImportError, AttributeError):
            pass

        extra_cmake_args = shlex.split(os.environ.get("OMNIUI_CMAKE_ARGS", ""))
        if extra_cmake_args:
            cmake_args.extend(extra_cmake_args)

        subprocess.check_call(
            [cmake, str(source_dir)] + cmake_args,
            cwd=str(build_dir),
        )

        # ---- CMake build ----
        default_build_jobs = "1" if IS_WINDOWS else str(os.cpu_count() or 1)
        build_jobs = os.environ.get("OMNIUI_BUILD_JOBS", default_build_jobs)
        build_args = [
            "--build", str(build_dir),
            "--parallel", build_jobs,
            "--config", "Release",
        ]
        subprocess.check_call([cmake] + build_args)

        # ---- Copy artifacts into the package directory ----
        pkg_dir.mkdir(parents=True, exist_ok=True)

        ext_suffix = sysconfig.get_config_var("EXT_SUFFIX")
        if not ext_suffix:
            ext_suffix = ".pyd" if IS_WINDOWS else ".so"

        # Library names. The shared binaries carry these names: the core is
        # libovui.so with the internal name libomni.ui.so (and a libomni.ui.so
        # file next to it), the scene library is libomni.ui.scene.so.
        if IS_WINDOWS:
            core_libs = ["ovui.dll", "omni.ui.dll"]
            standalone_lib = "omniui_standalone.dll"
        elif IS_MACOS:
            core_libs = ["libovui.dylib"]
            standalone_lib = "libomniui_standalone.dylib"
        else:
            core_libs = ["libovui.so", "libomni.ui.so"]
            standalone_lib = "libomniui_standalone.so"

        # Locate and copy the pybind11 modules: the shared _ui and the
        # standalone bridge _standalone.
        for module in ("_ui", "_standalone"):
            pybind_src = _find_artifact(build_dir, "bindings", f"{module}{ext_suffix}")
            if not pybind_src:
                raise RuntimeError(f"the build did not produce {module}{ext_suffix}")
            shutil.copy2(str(pybind_src), str(pkg_dir / f"{module}{ext_suffix}"))
            print(f"  copied {pybind_src.name} -> {pkg_dir / f'{module}{ext_suffix}'}")

        # Locate and copy the core shared library (a link is copied as a file)
        for core_lib in core_libs:
            core_src = _find_artifact(build_dir, "core", core_lib)
            if not core_src:
                raise RuntimeError(f"the build did not produce {core_lib}")
            shutil.copy2(str(core_src), str(pkg_dir / core_lib))
            print(f"  copied {core_src.name} -> {pkg_dir / core_lib}")

        # OVUI and its native consumers share one ImGui library.
        imgui_lib = "ovui_imgui.dll" if IS_WINDOWS else ("libimgui.dylib" if IS_MACOS else "libimgui.so")
        imgui_src = _find_artifact(build_dir, "third_party", imgui_lib)
        if not imgui_src:
            raise RuntimeError("the build did not produce the shared ImGui library")
        shutil.copy2(str(imgui_src), str(pkg_dir / imgui_lib))

        # Locate and copy the standalone shared library
        standalone_src = _find_artifact(build_dir, "standalone", standalone_lib)
        if standalone_src:
            shutil.copy2(str(standalone_src), str(pkg_dir / standalone_lib))
            print(f"  copied {standalone_src.name} -> {pkg_dir / standalone_lib}")

        # Ship the CUDA runtime the backend linked against. omniui_standalone
        # imports cudart directly and _ui links omniui_standalone, so without
        # it `import omni.ui` fails on any machine that has the NVIDIA driver
        # but not the CUDA Toolkit — which is the supported deployment. The
        # CUDA driver library is deliberately not packaged: it belongs to the
        # installed driver.
        runtime_record = build_dir / "cuda_runtime_path.txt"
        if runtime_record.exists():
            runtime_src = Path(runtime_record.read_text().strip())
            if not runtime_src.is_file():
                raise RuntimeError(
                    f"the build recorded a CUDA runtime at {runtime_src} but it "
                    "does not exist; the wheel would import only where a CUDA "
                    "Toolkit is installed"
                )
            runtime_src = runtime_src.resolve()
            # The loader's file, not the linker's. On Windows those are
            # different files — the link consumes cudart.lib while the backend
            # imports cudart64_<major>.dll — and shipping the wrong one yields
            # a wheel that installs cleanly and then fails to load.
            expected = "cudart64_*.dll" if IS_WINDOWS else "libcudart.so.*"
            if not fnmatch.fnmatch(runtime_src.name, expected):
                raise RuntimeError(
                    f"recorded CUDA runtime {runtime_src} is not a loadable "
                    f"runtime ({expected} expected); it cannot satisfy the "
                    "backend's import"
                )
            if IS_WINDOWS:
                runtime_name = runtime_src.name
            else:
                # Ship under the SONAME, not the resolved real name: the
                # backend's dependency is on libcudart.so.<major>.
                major = runtime_src.name.split(".so.")[1].split(".")[0]
                runtime_name = f"libcudart.so.{major}"
            shutil.copy2(str(runtime_src), str(pkg_dir / runtime_name))
            print(f"  copied CUDA runtime {runtime_src.name} -> {runtime_name}")

        # Also copy versioned shared lib files (Linux: .so.X.Y.Z, macOS: .X.Y.Z.dylib)
        if not IS_WINDOWS:
            for lib_name in ["libomniui_standalone"]:
                lib_dir = build_dir / "standalone"
                if IS_MACOS:
                    patterns = [f"{lib_name}.*.dylib"]
                else:
                    patterns = [f"{lib_name}.so.*"]
                for pattern in patterns:
                    for f in sorted(lib_dir.glob(pattern)):
                        target = pkg_dir / f.name
                        # Always overwrite: the pkg_dir may persist across builds
                        # (setuptools reuses build/lib.*/ between pip invocations),
                        # so a stale existence check would keep old binaries.
                        shutil.copy2(str(f), str(target))
                        print(f"  copied {f.name} -> {target}")

        # ---- Copy resource files ----
        resources_src = source_dir / "resources"
        resources_dst = pkg_dir / "resources"

        if resources_src.exists():
            # Fonts
            fonts_src = resources_src / "fonts"
            fonts_dst = resources_dst / "fonts"
            if fonts_src.exists():
                fonts_dst.mkdir(parents=True, exist_ok=True)
                # Clear stale font/license files from previous builds so files
                # removed from the source tree (e.g. NVIDIASans_*) don't linger
                # in editable installs — setuptools reuses build/lib.*/ across
                # pip invocations.
                for pattern in ("*.ttf", "*.txt", "*.md"):
                    for stale in fonts_dst.glob(pattern):
                        stale.unlink()
                    for src in fonts_src.glob(pattern):
                        shutil.copy2(str(src), str(fonts_dst / src.name))
                        print(f"  copied font asset {src.name}")

            # Glyphs
            glyphs_src = resources_src / "glyphs"
            glyphs_dst = resources_dst / "glyphs"
            if glyphs_src.exists() and any(glyphs_src.iterdir()):
                glyphs_dst.mkdir(parents=True, exist_ok=True)
                for svg in glyphs_src.glob("*.svg"):
                    shutil.copy2(str(svg), str(glyphs_dst / svg.name))
                    print(f"  copied glyph {svg.name}")

            # Twemoji atlas
            atlas_png = resources_src / "twemoji-atlas.png"
            atlas_json = resources_src / "twemoji-atlas.json"
            if atlas_png.exists():
                resources_dst.mkdir(parents=True, exist_ok=True)
                shutil.copy2(str(atlas_png), str(resources_dst / atlas_png.name))
                print(f"  copied {atlas_png.name}")
            if atlas_json.exists():
                resources_dst.mkdir(parents=True, exist_ok=True)
                shutil.copy2(str(atlas_json), str(resources_dst / atlas_json.name))
                print(f"  copied {atlas_json.name}")

        # ---- Copy Python source files ----
        py_src = source_dir / "python" / "omni" / "ui"
        for py_file in py_src.glob("*.py"):
            target = pkg_dir / py_file.name
            if not target.exists():
                shutil.copy2(str(py_file), str(target))
                print(f"  copied {py_file.name}")

        # markdown_providers subpackage
        providers_src = py_src / "markdown_providers"
        providers_dst = pkg_dir / "markdown_providers"
        if providers_src.exists():
            providers_dst.mkdir(parents=True, exist_ok=True)
            for py_file in providers_src.glob("*.py"):
                target = providers_dst / py_file.name
                shutil.copy2(str(py_file), str(target))
                print(f"  copied markdown_providers/{py_file.name}")

        # THIRD_PARTY_NOTICES.md from the repo root, bundled inside omni.ui
        # so it ships with the wheel and matching package_data picks it up.
        notices_src = REPO_ROOT / "THIRD_PARTY_NOTICES.md"
        if notices_src.exists():
            shutil.copy2(str(notices_src), str(pkg_dir / notices_src.name))
            print(f"  copied {notices_src.name}")

        # Install the native SDK from the configured build, not a separately
        # resolved dependency set. Clear only our generated SDK staging tree so
        # removed headers cannot survive a subsequent wheel build.
        sdk_dir = pkg_dir / "sdk"
        if sdk_dir.exists():
            shutil.rmtree(sdk_dir)
        subprocess.check_call([
            cmake, "--install", str(build_dir), "--config", "Release",
            "--component", "ovui-sdk", "--prefix", str(sdk_dir),
        ])
        sdk_manifest = {
            "source_commit": _PROJECT_COMMIT,
            "version": _QUALIFIED_VERSION,
            "files": {
                path.relative_to(sdk_dir).as_posix(): hashlib.sha256(path.read_bytes()).hexdigest()
                for path in sorted(sdk_dir.rglob("*")) if path.is_file()
            },
        }
        (sdk_dir / "manifest.json").write_text(
            json.dumps(sdk_manifest, indent=2) + "\n", encoding="utf-8"
        )

        # ---- Generate and bundle SBOM ----
        self._generate_sbom(build_dir, pkg_dir)

        # ---- Copy omni.ui_scene artifacts ----
        # _scene and the scene library go into a sibling omni/ui_scene/ dir.
        scene_pkg_dir = pkg_dir.parent / "ui_scene"
        scene_pkg_dir.mkdir(parents=True, exist_ok=True)

        if IS_WINDOWS:
            scene_lib = "omni.ui.scene.dll"
        elif IS_MACOS:
            scene_lib = "libomni.ui.scene.dylib"
        else:
            scene_lib = "libomni.ui.scene.so"

        # pybind11 scene module
        scene_pybind_src = _find_artifact(build_dir, "bindings", f"_scene{ext_suffix}")
        if not scene_pybind_src:
            raise RuntimeError(f"the build did not produce _scene{ext_suffix}")
        shutil.copy2(str(scene_pybind_src), str(scene_pkg_dir / f"_scene{ext_suffix}"))
        print(f"  copied {scene_pybind_src.name} -> {scene_pkg_dir / f'_scene{ext_suffix}'}")

        # scene shared library
        scene_lib_src = _find_artifact(build_dir, "core", scene_lib)
        if not scene_lib_src:
            raise RuntimeError(f"the build did not produce {scene_lib}")
        shutil.copy2(str(scene_lib_src), str(scene_pkg_dir / scene_lib))
        print(f"  copied {scene_lib_src.name} -> {scene_pkg_dir / scene_lib}")

        # Prebuilt mode: the shared binaries come from another build of the
        # same sources instead of this CMake build.
        prebuilt = os.environ.get("OVUI_PREBUILT_DIR", "").strip()
        if prebuilt:
            _use_prebuilt_shared(Path(prebuilt), pkg_dir, scene_pkg_dir, core_libs, scene_lib, ext_suffix)

        # Python source files for the scene package
        scene_py_src = source_dir / "python" / "omni" / "ui_scene"
        for py_file in scene_py_src.glob("*.py"):
            target = scene_pkg_dir / py_file.name
            if not target.exists():
                shutil.copy2(str(py_file), str(target))
                print(f"  copied scene {py_file.name}")


class BuildPyWithAgentSkills(build_py):
    """Bundle repo-owned Agent Skills without moving their source trees."""

    def run(self) -> None:
        super().run()
        # The .pth and its module sit at the wheel root, so site imports
        # them at startup (see python/_ovui_imgui_preload.py).
        for name in ("ovui_imgui_preload.pth", "_ovui_imgui_preload.py"):
            shutil.copy2(Path(__file__).resolve().parent / "python" / name, Path(self.build_lib) / name)
        source_root = REPO_ROOT / "skills"
        target_root = Path(self.build_lib) / "ovui_agent_skills" / "skills"
        if target_root.exists():
            shutil.rmtree(target_root)

        shutil.copytree(
            source_root / "omniverse-ui-apis",
            target_root / "omniverse-ui-apis",
        )

        inspector_source = source_root / "omniverse-ui-inspector"
        inspector_target = target_root / "omniverse-ui-inspector"
        inspector_target.mkdir(parents=True)
        for filename in ("SKILL.md", "requirements.txt"):
            shutil.copy2(inspector_source / filename, inspector_target / filename)
        for dirname in ("references", "scripts", "ovuiinspect"):
            shutil.copytree(
                inspector_source / dirname,
                inspector_target / dirname,
                ignore=shutil.ignore_patterns("__pycache__", "*.pyc", "*.pyo"),
            )


